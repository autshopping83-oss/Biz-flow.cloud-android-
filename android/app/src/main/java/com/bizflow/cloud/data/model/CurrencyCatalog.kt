    fun byCode(code: String): Currency? =
        ALL.firstOrNull { it.code.equals(code, ignoreCase = true) }

    /**
     * Pesquisa instantanea por codigo ISO, nome da moeda, simbolo ou
     * pais/territorio associado. Ordem deterministica (por codigo ISO).
     */
    fun search(query: String): List<Currency> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return ALL
        return ALL.filter { c ->
            c.code.lowercase().contains(q) ||
                c.name.lowercase().contains(q) ||
                c.symbol.lowercase().contains(q) ||
                CurrencyCountries.forCode(c.code).any { it.lowercase().contains(q) }
        }
    }

