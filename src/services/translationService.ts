export const getTranslation = (lang: string, key: string): string => {
  const translations = TRANSLATIONS[lang];
  if (translations) return (translations as Record<string, string>)[key] || key;
  // Fallback neutro e internacional (inglês) quando o idioma não está disponível
  const fallback = TRANSLATIONS['en'];
  return (fallback as Record<string, string>)[key] || key;
};

// Resolve o idioma ativo: usa o idioma preferido (da Empresa) se disponível;
// pré-login recorre ao idioma do sistema/dispositivo; senão, inglês (neutro).
export const resolveLanguage = (preferred?: string): string => {
  if (preferred && TRANSLATIONS[preferred]) return preferred;
  try {
    const nav = typeof navigator !== 'undefined' ? navigator.language : '';
    const tag = (nav || '').split('-')[0].toLowerCase();
    if (TRANSLATIONS[tag]) return tag;
  } catch {
    // ignora erros de acesso a navigator
  }
  return 'en';
};

export const formatMoney = (amount: number, currencyCode?: string, lang?: string) => {
  if (!currencyCode) {
    // Sem moeda configurada: apenas formata o número, sem assumir símbolo/código
    return amount.toLocaleString(lang || undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 });
  }
  try {
    return new Intl.NumberFormat(lang || undefined, {
      style: 'currency',
      currency: currencyCode,
    }).format(amount);
  } catch (e) {
    // Fallback se o código de moeda for inválido
    return `${amount.toFixed(2)} ${currencyCode}`;
  }
};